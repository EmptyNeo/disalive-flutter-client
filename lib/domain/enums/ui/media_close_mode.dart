/// Как экран должен закрыться:
/// - [toSource] — точный обратный полёт к прямоугольнику, откуда открыли
///   (актуально, если во время просмотра остались на том же сообщении).
/// - [collapseUp] / [collapseDown] — стилизованное схлопывание вверх/вниз
///   без привязки к реальным координатам нового сообщения в списке (мы
///   намеренно их не ищем").
enum MediaCloseMode { toSource, collapseUp, collapseDown }